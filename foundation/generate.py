#!/usr/bin/env python3
"""Render the TS3 styles and plugin constants from the shared Foundation tokens."""

import argparse
import json
import re
from pathlib import Path
from string import Template

FOUNDATION = Path(__file__).resolve().parent
ROOT = FOUNDATION.parent
STYLES = ROOT / "src" / "styles"
THEMES = (("flat_white", "Flat White"), ("flat_dark", "Flat Dark"))
TEMPLATES = {
    "widgets.qss.in": "{folder}.qss",
    "richtext.qss.in": "{folder}_chat.qss",
    "tree_tooltip_channel.tpl.in": "{folder}/tree_tooltip_channel.tpl",
    "tree_tooltip_client.tpl.in": "{folder}/tree_tooltip_client.tpl",
}


def load_tokens():
    tokens = json.loads((FOUNDATION / "tokens.json").read_text(encoding="utf-8"))
    for name in (*tokens["colors"], *tokens["metrics"]):
        if not re.fullmatch(r"[a-z][a-zA-Z0-9]*", name):
            raise ValueError(f"Invalid token name: {name}")
    if tokens["colors"].keys() & tokens["metrics"].keys():
        raise ValueError("Color and metric tokens must have distinct names")
    for name, pair in tokens["colors"].items():
        if len(pair) != len(THEMES) or not all(re.fullmatch(r"#[0-9A-F]{6}", color) for color in pair):
            raise ValueError(f"Expected a light/dark RGB pair for {name}")
    for name, value in tokens["metrics"].items():
        if type(value) is not int or value <= 0:
            raise ValueError(f"Expected a positive integer for {name}")
    if not re.fullmatch(r"[\w -]+", tokens["fontFamily"], re.ASCII):
        raise ValueError("Invalid font family")
    return tokens


def luminance(color):
    channels = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in channels]
    return sum(c * weight for c, weight in zip(linear, (0.2126, 0.7152, 0.0722)))


def check_contrast(theme, values):
    pairs = (
        ("textPrimary", ("bgCanvas", "bgSurface", "bgSidebar", "bgControl", "bgInput",
                         "bgInputFocus", "bgOverlay", "fillHover", "fillPressed", "fillSelected",
                         "fillAccentSubtle", "bgBubbleOther")),
        ("textSecondary", ("bgCanvas", "bgSurface", "bgSidebar", "bgOverlay")),
        ("textTertiary", ("bgSurface", "bgSidebar", "bgOverlay", "bgInput")),
        ("accent", ("bgCanvas", "bgSurface", "bgSidebar", "bgOverlay", "fillHover",
                    "fillSelected", "fillAccentSubtle")),
        ("selectionText", ("selectionBg", "accent")),
        ("textDanger", ("bgSurface", "bgTooltip")),
        ("textWarning", ("bgSurface",)),
        ("textOnAccent", ("accent", "accentHover", "accentPressed")),
        ("textTooltip", ("bgTooltip",)),
        ("textOnDanger", ("fillDanger",)),
    )
    for foreground, backgrounds in pairs:
        for background in backgrounds:
            low, high = sorted((luminance(values[foreground]), luminance(values[background])))
            ratio = (high + 0.05) / (low + 0.05)
            if ratio < 4.5:
                raise ValueError(f"{theme}: {foreground} on {background} is {ratio:.2f}:1 (needs 4.5:1)")


def render_header(tokens):
    colors = tokens["colors"]
    roles = "\n".join(f"    {role}," for role in colors)
    entries = "\n".join(f"    {{0x{light[1:]}, 0x{dark[1:]}}},  // {role}"
                        for role, (light, dark) in colors.items())
    metrics = "\n".join(f"inline constexpr int {name} = {value};"
                        for name, value in tokens["metrics"].items())
    return f'''// Generated by foundation/generate.py from foundation/tokens.json.
#pragma once

#include <cstddef>
#include <QColor>

namespace foundation {{

enum class Color {{
{roles}
    Count,
}};

inline constexpr QRgb colors[][2] = {{
{entries}
}};
static_assert(sizeof(colors) / sizeof(colors[0]) == static_cast<std::size_t>(Color::Count));

inline QColor color(Color role, bool dark) {{
    return QColor::fromRgb(colors[static_cast<std::size_t>(role)][dark ? 1 : 0]);
}}

inline constexpr char fontFamily[] = "{tokens['fontFamily']}";
{metrics}

}}  // namespace foundation
'''


def render():
    tokens = load_tokens()
    files = {ROOT / "plugin" / "src" / "foundation_tokens.h": render_header(tokens)}
    templates = {name: Template((FOUNDATION / name).read_text(encoding="utf-8"))
                 for name in TEMPLATES}
    for index, (folder, theme) in enumerate(THEMES):
        palette = {role: colors[index] for role, colors in tokens["colors"].items()}
        check_contrast(theme, palette)
        values = dict(palette, **tokens["metrics"], fontFamily=tokens["fontFamily"],
                      folder=folder, theme=theme,
                      # Qt's minimum height describes the content box. Both the
                      # border and vertical padding are added outside it.
                      controlContentHeight=tokens["metrics"]["controlHeight"]
                      - 2 * (tokens["metrics"]["gapTight"] + 1))
        for name, output in TEMPLATES.items():
            text = templates[name].substitute(values)
            for resource in re.findall(r"url\(['\"]styles:([^'\"]+)['\"]\)", text):
                if not resource.startswith(f"{folder}/") or not (STYLES / resource).is_file():
                    raise ValueError(f"{theme}: missing or mismatched stylesheet resource {resource}")
            files[STYLES / output.format(folder=folder)] = text
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files without writing them")
    args = parser.parse_args()
    stale = []
    try:
        for path, text in render().items():
            if path.is_file() and path.read_text(encoding="utf-8") == text:
                continue
            if args.check:
                stale.append(path.relative_to(ROOT).as_posix())
            else:
                path.write_text(text, encoding="utf-8", newline="\n")
    except (OSError, KeyError, ValueError) as error:
        parser.exit(1, f"Foundation: {error}\n")
    if stale:
        parser.exit(1, "Stale Foundation output (run python foundation/generate.py):\n"
                    + "\n".join(stale) + "\n")
    print("Foundation styles and plugin tokens are up to date.")


if __name__ == "__main__":
    main()
